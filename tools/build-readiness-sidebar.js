// Generates readiness sidebar assets from controlled QMD front-matter metadata.

const root = Deno.cwd();
const frontMatterPattern = /^---\r?\n([\s\S]*?)\r?\n---/;
const readinessPattern = /^\s*readiness\s*:\s*([a-z_]+)\s*(?:#.*)?$/m;
const allowed = new Set([
  "not_reviewed",
  "context_only",
  "blocked",
  "partially_implementable",
  "ready_with_declared_uncertainty",
  "ready",
]);
const skipDirs = new Set([
  "_site", ".quarto", ".git", ".venv", ".uv-cache", ".uv-python",
  "__pycache__", "node_modules",
]);

function findQmdFiles(dir) {
  const files = [];
  for (const entry of Deno.readDirSync(dir)) {
    const entryPath = dir + "/" + entry.name;
    if (entry.isDirectory) {
      if (!skipDirs.has(entry.name)) files.push(...findQmdFiles(entryPath));
    } else if (entry.isFile && entry.name.endsWith(".qmd")) {
      files.push(entryPath);
    }
  }
  return files;
}

const entries = [];
for (const file of findQmdFiles(root)) {
  const source = Deno.readTextFileSync(file);
  const frontMatter = source.match(frontMatterPattern);
  const match = frontMatter && frontMatter[1].match(readinessPattern);
  const relativePath = file.slice(root.length).replace(/^[\\/]+/, "").replace(/\\/g, "/");
  if (!match) throw new Error("Missing readiness field: " + relativePath);
  if (!allowed.has(match[1])) throw new Error("Invalid readiness '" + match[1] + "': " + relativePath);
  entries.push({ path: relativePath.replace(/\.qmd$/, ".html"), status: match[1] });
}
entries.sort((a, b) => a.path.localeCompare(b.path));

const browserSource = String.raw`// Generated by tools/build-readiness-sidebar.js. Edit readiness in page front matter.
(() => {
  const entries = __READINESS_ENTRIES__;
  const definitions = {
    not_reviewed: { label: "Not reviewed", detail: "This page has not yet completed the structured model review.", rank: 0 },
    blocked: { label: "Blocked", detail: "Material missing inputs or decisions prevent implementation.", rank: 1 },
    partially_implementable: { label: "Partial", detail: "Part of the calculation can be implemented, but material gaps remain.", rank: 2 },
    ready_with_declared_uncertainty: { label: "Ready — uncertain", detail: "Implementable with material uncertainty explicitly declared.", rank: 3 },
    ready: { label: "Ready", detail: "Implementable from the documented inputs and assumptions.", rank: 4 },
    context_only: { label: "Context", detail: "Context page; no standalone model calculation is expected.", rank: 5 },
  };
  const statusByPath = new Map(entries.map(({ path, status }) => [path, status]));
  const sortedPaths = [...statusByPath.keys()].sort((a, b) => b.length - a.length);

  function statusForHref(href) {
    if (!href) return null;
    let pathname;
    try { pathname = decodeURIComponent(new URL(href, window.location.href).pathname); }
    catch { return null; }
    pathname = pathname.replace(/\\/g, "/").replace(/\/+$/, "");
    for (const path of sortedPaths) {
      if (pathname.endsWith("/" + path) || pathname.endsWith(path)) return statusByPath.get(path);
    }
    return null;
  }

  function applyStatus(link, status, prefix) {
    if (!link || !definitions[status]) return;
    link.dataset.readiness = status;
    const name = link.querySelector(".menu-text")?.textContent?.trim() || link.textContent.trim();
    const category = prefix || "Model readiness";
    link.title = name + " — " + category + ": " + definitions[status].label + ". " + definitions[status].detail;
    link.setAttribute("aria-label", name + ". " + category + ": " + definitions[status].label + ".");
  }

  function applySidebarReadiness() {
    document.querySelectorAll("#quarto-sidebar a.sidebar-link[href]").forEach((link) => {
      applyStatus(link, statusForHref(link.getAttribute("href")));
    });
    document.querySelectorAll("#quarto-sidebar .sidebar-item-section").forEach((section) => {
      const statuses = [...section.querySelectorAll("ul.sidebar-section a.sidebar-link[data-readiness]")]
        .map((link) => link.dataset.readiness)
        .filter((status) => status !== "context_only");
      if (!statuses.length) return;
      statuses.sort((a, b) => definitions[a].rank - definitions[b].rank);
      const sectionLink = section.querySelector(":scope > .sidebar-item-container > .sidebar-link");
      applyStatus(sectionLink, statuses[0], "Least-ready child page");
    });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", applySidebarReadiness);
  else applySidebarReadiness();
})();
`;
const script = browserSource.replace("__READINESS_ENTRIES__", JSON.stringify(entries));

const html = String.raw`<!-- Generated by tools/build-readiness-sidebar.js. -->
<script>
(() => {
  if (document.querySelector("script[data-readiness-sidebar]")) return;
  const stylesHref = [...document.querySelectorAll('link[rel="stylesheet"][href]')]
    .map((link) => link.getAttribute("href"))
    .find((href) => /(^|\/|\.\.\/)styles\.css(?:[?#].*)?$/.test(href));
  const rootPath = stylesHref ? stylesHref.replace(/styles\.css(?:[?#].*)?$/, "") : "";
  const script = document.createElement("script");
  script.src = rootPath + "readiness-sidebar.js";
  script.defer = true;
  script.dataset.readinessSidebar = "true";
  document.body.appendChild(script);
})();
</script>
`;

function writeIfChanged(path, value) {
  try { if (Deno.readTextFileSync(path) === value) return; }
  catch (error) { if (!(error instanceof Deno.errors.NotFound)) throw error; }
  Deno.writeTextFileSync(path, value);
}

writeIfChanged(root + "/readiness-sidebar.js", script);
writeIfChanged(root + "/readiness-sidebar.html", html);
