// Generates evidence-status assets from controlled bibliography keywords.

const root = Deno.cwd();
const source = Deno.readTextFileSync(root + "/references.bib");
const starts = [...source.matchAll(/^@\w+\{([^,]+),/gm)];
const allowedAccess = new Set(["access-public", "access-controlled-internal", "access-unresolved"]);
const allowedUse = new Set(["use-adopted", "use-validation-only", "use-background-only", "use-unresolved"]);
const entries = [];

for (let index = 0; index < starts.length; index++) {
  const key = starts[index][1];
  const start = starts[index].index;
  const end = index + 1 < starts.length ? starts[index + 1].index : source.length;
  const block = source.slice(start, end);
  const keywordMatch = block.match(/^\s*keywords\s*=\s*\{([^}]*)\}/m);
  if (!keywordMatch) throw new Error("Missing evidence keywords: " + key);
  const keywords = keywordMatch[1].split(",").map((value) => value.trim());
  const access = keywords.filter((value) => allowedAccess.has(value));
  const use = keywords.filter((value) => allowedUse.has(value));
  if (access.length !== 1 || use.length !== 1) {
    throw new Error("Expected one access and one use class: " + key);
  }
  entries.push({ key, access: access[0], use: use[0] });
}
entries.sort((a, b) => a.key.localeCompare(b.key));

const browserSource = String.raw`// Generated by tools/build-evidence-status.js. Edit keywords in references.bib.
(() => {
  const entries = __EVIDENCE_ENTRIES__;
  const definitions = {
    "access-public": { label: "Public", detail: "Publicly accessible evidence record." },
    "access-controlled-internal": { label: "Controlled internal", detail: "Access requires the controlled project source." },
    "access-unresolved": { label: "Access unresolved", detail: "The exact accessible source record is incomplete." },
    "use-adopted": { label: "Adopted", detail: "Supports an adopted input, method, boundary, or model-relevant claim." },
    "use-validation-only": { label: "Validation only", detail: "Used to test or contextualise a result, not as the adopted model input." },
    "use-background-only": { label: "Background only", detail: "Retained for context but not used by the current model documentation." },
    "use-unresolved": { label: "Use unresolved", detail: "No final model use has been established." },
  };
  const byKey = new Map(entries.map((entry) => [entry.key, entry]));

  function badge(value, dimension) {
    const span = document.createElement("span");
    span.className = "evidence-badge evidence-" + dimension + " " + value;
    span.textContent = definitions[value].label;
    span.title = definitions[value].detail;
    return span;
  }

  function decorateReferences() {
    const references = document.querySelectorAll("#refs .csl-entry[id^='ref-']");
    references.forEach((reference) => {
      const key = decodeURIComponent(reference.id.slice(4));
      const entry = byKey.get(key);
      if (!entry || reference.querySelector(".evidence-badges")) return;
      const wrapper = document.createElement("span");
      wrapper.className = "evidence-badges";
      wrapper.setAttribute("aria-label", "Evidence status");
      wrapper.append(badge(entry.access, "access"), badge(entry.use, "use"));
      reference.appendChild(wrapper);
    });

    const summary = document.getElementById("evidence-status-summary");
    if (summary && !summary.dataset.rendered) {
      const counts = {};
      entries.forEach(({ access, use }) => {
        counts[access] = (counts[access] || 0) + 1;
        counts[use] = (counts[use] || 0) + 1;
      });
      const text = [
        entries.length + " catalog records",
        counts["use-adopted"] + " adopted",
        counts["use-validation-only"] + " validation only",
        counts["use-background-only"] + " background only",
        counts["use-unresolved"] + " unresolved use",
        counts["access-controlled-internal"] + " controlled internal",
        counts["access-unresolved"] + " unresolved access",
      ].join(" · ");
      summary.textContent = text;
      summary.dataset.rendered = "true";
    }
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", decorateReferences);
  else decorateReferences();
})();
`;
const script = browserSource.replace("__EVIDENCE_ENTRIES__", JSON.stringify(entries));

const html = String.raw`<!-- Generated by tools/build-evidence-status.js. -->
<script>
(() => {
  if (document.querySelector("script[data-evidence-status]")) return;
  const stylesHref = [...document.querySelectorAll('link[rel="stylesheet"][href]')]
    .map((link) => link.getAttribute("href"))
    .find((href) => /(^|\/|\.\.\/)styles\.css(?:[?#].*)?$/.test(href));
  const rootPath = stylesHref ? stylesHref.replace(/styles\.css(?:[?#].*)?$/, "") : "";
  const script = document.createElement("script");
  script.src = rootPath + "evidence-status.js";
  script.defer = true;
  script.dataset.evidenceStatus = "true";
  document.body.appendChild(script);
})();
</script>
`;

function writeIfChanged(path, value) {
  try { if (Deno.readTextFileSync(path) === value) return; }
  catch (error) { if (!(error instanceof Deno.errors.NotFound)) throw error; }
  Deno.writeTextFileSync(path, value);
}

writeIfChanged(root + "/evidence-status.js", script);
writeIfChanged(root + "/evidence-status.html", html);
