"""Generate the platform evidence table and figure from canonical inputs.

Called by build_model_variables.py; does not adopt a platform cost in the model.
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from model.platforms.platform_material_capex import commercial_benchmarks, benchmark_cost_eur2025


def build(inputs, root: Path):
    rows = commercial_benchmarks(inputs)
    ref = inputs.reference_number
    cost = lambda key: f"{ref(key) / 1e6:,.1f} million {inputs.parameters.get(key).unit}"
    sources = [
        ("HKZ Alpha + Beta", f"{ref('platform-hkz-count'):g} × {ref('platform-hkz-power'):g} GW",
         cost('platform-hkz-contract'), "2019 (aggregate announcement; Alpha awarded earlier)",
         "Offshore EPCI; owner-procured HV equipment. [@petrofac2019HKZ; @tennet2021OwnerEquipment]"),
        ("Nederwiek 1", f"{ref('platform-mhb-power'):g} GW", cost('platform-nederwiek-petrofac'), "2023 (award)",
         "Petrofac share includes offshore and onshore works; offshore allocation is assumed. [@petrofac2023Nederwiek]"),
        ("Petrofac framework", f"{ref('platform-petrofac-systems'):g} systems", cost('platform-petrofac-framework'), "2023 (announcement)",
         "Both partners, both ends; allocated average is not an independent observation. [@petrofac2023Framework; @petrofac2025Prospectus]"),
        ("NSE / Iv concept", f"{ref('platform-nse-power'):g} GW", cost('platform-nse-structure-cost'), "2022 (publication assumed)",
         "Structure including installation, excluding process-equipment purchase. [@nse2022EnergyHubs, table 4.9 and sec. 4.4.2]"),
        ("OffsH2ore concept", f"{ref('platform-offsh2ore-power'):g} GW", cost('platform-offsh2ore-cost'), "2023 (publication assumed)",
         "Structure, piping and installation; further engineering allowance separate. [@offsh2ore2023Report, p. 79]"),
        ("MHB Alpha subcontract", f"{ref('platform-mhb-power'):g} GW", cost('platform-mhb-contract'), "2023 (award)",
         "Construction engineering, fabrication, mechanical completion, load-out, sea fastening and architectural work; not full EPCI. [@mhb2023AlphaAward]"),
    ]
    text = ["<!-- Generated by tools/build_platform_benchmarks.py; edit inputs or builder. -->", "",
            "### Published costs and scope", "",
            "| Reference | Capacity / count | Published package cost | Price-year basis | Scope and source |",
            "|---|---|---|---|---|"]
    text += ["| " + " | ".join(row) + " |" for row in sources]
    text += ["", "### Reconstructed comparison on the common price basis", "",
             "All costs below are EUR~2025~. Masses are complete topsides, including equipment and structure. HKZ is a per-platform average of one combined award; the framework uses Alpha's mass as a representative reference, not six matched project weights.", "",
             "| Reference | Topside (t) | Cost (million EUR~2025~) | EUR~2025~/topside t | Topside t/kW | EUR~2025~/kW |",
             "|---|---:|---:|---:|---:|---:|"]
    for r in rows:
        text.append(f"| {r['name']} | {r['topside_t']:,.0f} | {r['cost_eur2025']/1e6:,.0f} | {r['eur_per_topside_t']:,.0f} | {r['topside_t_per_kw']:.5f} | {r['eur_per_kw']:,.0f} |")
    text += ["", "Mass evidence: HKZ Alpha [@petrofac2021HKZAlpha], HKZ Beta [@petrofac2022HKZBeta], Nederwiek [@misc2024Nederwiek, printed p. 77], Alpha [@mhb2023AlphaAward], NSE [@nse2022EnergyHubs, table 4.9], and OffsH2ore [@offsh2ore2023Report, p. 48]. Capacity denominators are the stated platform ratings; they are not necessarily identical electrical input boundaries across technologies.", ""]

    low, high, central = [benchmark_cost_eur2025(inputs.number("platform-epci-topside-unit-cost-source" if key == "central" else f"platform-benchmark-topside-linear-{key}", "EUR/t"), 1, 2023, inputs)
                          for key in ("low", "high", "central")]
    inflation = benchmark_cost_eur2025(1, 1, 2023, inputs)
    hkz_factor = benchmark_cost_eur2025(1, 1, 2019, inputs)
    annual = "; ".join(f"{year}: {inputs.number(f'platform-benchmark-hicp-{year}')*100:g}%" for year in range(2020, 2026))
    text += ["### Currency and price-year audit", "",
             f"Annual-average exchange rates per EUR: USD {inputs.number('platform-benchmark-usd-eur-2019'):.4f} (2019), USD {inputs.number('platform-benchmark-usd-eur-2023'):.4f} and MYR {inputs.number('platform-benchmark-myr-eur-2023'):.4f} (2023) [@bundesbank2026AnnualFX]. Euro-area annual HICP changes: {annual} [@eurostat2026AnnualHICP].",
             "", f"The resulting inflation factors to 2025 are {hkz_factor:.5f} from 2019, {benchmark_cost_eur2025(1, 1, 2022, inputs):.5f} from 2022, and {inflation:.5f} from 2023. Source-year conversion precedes inflation adjustment. Consumer inflation is a transparent preliminary proxy, not an offshore fabrication or installation index.", "",
             f"HKZ: divide the combined award and summed topside masses by {ref('platform-hkz-count'):g}, convert USD to EUR at the assumed aggregate price year, then escalate. Nederwiek: multiply Petrofac's own award by the assumed offshore share of {inputs.fraction('platform-benchmark-offshore-share'):.0%}, convert and escalate. Framework: divide the framework value by {ref('platform-petrofac-systems'):g}, multiply by the approximate Petrofac share of {inputs.fraction('platform-benchmark-petrofac-share'):.0%} and the same offshore share, then escalate. The latter share is user-selected modelling judgement, not a supplier disclosure.", ""]
    out = root / "platforms" / "_generated"
    out.mkdir(exist_ok=True)
    (out / "benchmarks.md").write_text("\n".join(text), encoding="utf-8")

    fig, ax = plt.subplots(figsize=(10.8, 7.2), layout="constrained")
    x = np.linspace(0, max(r['topside_t'] for r in rows)*1.15, 150)
    ax.plot(x/1000, x*low/1e6, "--", color="#64748b", label=f"Illustrative linear relation: EUR {low:,.0f}/t (not fitted)")
    styles = {"award": ("o", "#156f87", True), "allocated": ("D", "#156f87", True),
              "framework": ("s", "#156f87", False), "study": ("^", "#c77713", False),
              "fabrication": ("x", "#8b919a", True)}
    labels = {"hkz": ("HKZ average: offshore EPCI", (-35, 65)),
              "nederwiek": ("Nederwiek: allocated offshore EPCI", (-200, 25)),
              "framework": ("Framework: allocated average", (-185, -30)),
              "nse": ("NSE / Iv: design estimate", (-30, 60)),
              "offsh2ore": ("OffsH2ore: design estimate", (15, -15)),
              "mhb": ("MHB Alpha: fabrication only", (-170, 25))}
    for r in rows:
        marker, color, filled = styles[r['kind']]
        kwargs = {"color": color} if filled else {"facecolors": "none", "edgecolors": color}
        ax.scatter(r['topside_t']/1000, r['cost_eur2025']/1e6, marker=marker, s=75, zorder=4, **kwargs)
        label, offset = labels[r['key']]
        ax.annotate(label, (r['topside_t']/1000, r['cost_eur2025']/1e6), xytext=offset,
                    textcoords="offset points", fontsize=9,
                    arrowprops={"arrowstyle": "-", "color": "#a8b4c0"})
    ax.set(xlim=(0, x[-1]/1000), ylim=(0, max(r['cost_eur2025'] for r in rows)/1e6*1.2),
           xlabel="Complete topside mass per platform (1,000 t)", ylabel="Cost (million EUR 2025)",
           title="Platform cost versus complete topside mass\nDifferent scopes shown separately; equipment and structure included in mass")
    ax.grid(alpha=.2); ax.set_axisbelow(True); ax.legend(loc="upper left", fontsize=9)
    fig.savefig(root / "figures" / "platform_epci_benchmarks.svg", metadata={"Date": None})
    plt.close(fig)
    return {"platform-benchmark-low-2025": f"{low:,.0f}", "platform-benchmark-high-2025": f"{high:,.0f}",
            "platform-benchmark-central-2025": f"{central:,.0f}",
            "platform-benchmark-hkz-rate": f"{rows[0]['eur_per_topside_t']:,.0f}",
            "platform-benchmark-nederwiek-rate": f"{rows[1]['eur_per_topside_t']:,.0f}"}
