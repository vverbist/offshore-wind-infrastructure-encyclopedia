// Generates progress-sidebar.js and progress-sidebar.html from the `completion:`
// front matter field on each .qmd page. Run automatically by Quarto's pre-render
// hook (see _quarto.yml) via Quarto's own bundled runtime, so no separate
// interpreter needs to be installed on any platform.

const root = Deno.cwd();

const frontMatterPattern = /^---\r?\n([\s\S]*?)\r?\n---/;
const progressPattern = /^\s*completion\s*:\s*(-?\d+(?:\.\d+)?)\s*(?:#.*)?$/m;

const SKIP_DIRS = new Set([
  "_site",
  ".quarto",
  ".git",
  ".venv",
  ".uv-cache",
  ".uv-python",
  "__pycache__",
  "node_modules",
]);

function findQmdFiles(dir) {
  const files = [];
  for (const entry of Deno.readDirSync(dir)) {
    const entryPath = `${dir}/${entry.name}`;
    if (entry.isDirectory) {
      if (SKIP_DIRS.has(entry.name)) continue;
      files.push(...findQmdFiles(entryPath));
    } else if (entry.isFile && entry.name.endsWith(".qmd")) {
      files.push(entryPath);
    }
  }
  return files;
}

function bucketProgress(progress) {
  const clamped = Math.min(100, Math.max(0, progress));
  return Math.round(clamped / 10) * 10;
}

const entries = [];

for (const file of findQmdFiles(root)) {
  const text = Deno.readTextFileSync(file);

  const frontMatterMatch = text.match(frontMatterPattern);
  if (!frontMatterMatch) continue;

  const progressMatch = frontMatterMatch[1].match(progressPattern);
  if (!progressMatch) continue;

  const relativePath = file
    .slice(root.length)
    .replace(/^[\\/]+/, "")
    .replace(/\\/g, "/");
  const htmlPath = relativePath.replace(/\.qmd$/, ".html");

  entries.push({ path: htmlPath, progress: bucketProgress(Number(progressMatch[1])) });
}

entries.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

const progressJson = JSON.stringify(entries);

const script = `// Generated by tools/build-progress-sidebar.js. Edit completion in page front matter.
(() => {
  const entries = ${progressJson};
  const alphaByProgress = new Map([
    [0, 0.16],
    [10, 0.24],
    [20, 0.32],
    [30, 0.40],
    [40, 0.48],
    [50, 0.56],
    [60, 0.64],
    [70, 0.74],
    [80, 0.84],
    [90, 0.92],
    [100, 1.00],
  ]);

  const progressByPath = new Map(
    entries.map(({ path, progress }) => [path, normaliseProgress(progress)])
  );

  const sortedPaths = [...progressByPath.keys()].sort((a, b) => b.length - a.length);

  function normaliseProgress(progress) {
    const numericProgress = Number(progress);
    if (!Number.isFinite(numericProgress)) {
      return null;
    }

    const clampedProgress = Math.min(100, Math.max(0, numericProgress));
    return Math.round(clampedProgress / 10) * 10;
  }

  function progressForHref(href) {
    if (!href) {
      return null;
    }

    let pathname;

    try {
      pathname = decodeURIComponent(new URL(href, window.location.href).pathname);
    } catch {
      return null;
    }

    pathname = pathname.replace(/\\\\/g, "/").replace(/\\/+$/, "");

    for (const path of sortedPaths) {
      if (pathname.endsWith("/" + path) || pathname.endsWith(path)) {
        return progressByPath.get(path);
      }
    }

    return null;
  }

  function applyProgress(link, progress, label) {
    if (!link || progress === null) {
      return;
    }

    const alpha = alphaByProgress.get(progress) ?? 1;
    const text = link.textContent.trim();

    link.dataset.progress = String(progress);
    link.style.setProperty("--progress-alpha", String(alpha));
    link.setAttribute("title", \`\${text}: \${progress}% \${label}\`);
  }

  function applySidebarProgress() {
    document.querySelectorAll("#quarto-sidebar a.sidebar-link[href]").forEach((link) => {
      applyProgress(link, progressForHref(link.getAttribute("href")), "complete");
    });

    document.querySelectorAll("#quarto-sidebar .sidebar-item-section").forEach((section) => {
      const childLinks = [
        ...section.querySelectorAll("ul.sidebar-section a.sidebar-link[data-progress]"),
      ];

      if (childLinks.length === 0) {
        return;
      }

      const averageProgress = childLinks.reduce(
        (sum, link) => sum + Number(link.dataset.progress),
        0
      ) / childLinks.length;

      const sectionLink = section.querySelector(
        ":scope > .sidebar-item-container > .sidebar-link"
      );

      applyProgress(sectionLink, normaliseProgress(averageProgress), "average complete");
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", applySidebarProgress);
  } else {
    applySidebarProgress();
  }
})();
`;

const html = `<!-- Generated by tools/build-progress-sidebar.js. -->
<script>
(() => {
  if (document.querySelector("script[data-progress-sidebar]")) {
    return;
  }

  const stylesHref = [...document.querySelectorAll('link[rel="stylesheet"][href]')]
    .map((link) => link.getAttribute("href"))
    .find((href) => /(^|\\/|\\.\\.\\/)styles\\.css(?:[?#].*)?$/.test(href));

  const rootPath = stylesHref ? stylesHref.replace(/styles\\.css(?:[?#].*)?$/, "") : "";
  const script = document.createElement("script");

  script.src = rootPath + "progress-sidebar.js";
  script.defer = true;
  script.dataset.progressSidebar = "true";

  document.body.appendChild(script);
})();
</script>
`;

function writeTextFileIfChanged(path, content) {
  try {
    if (Deno.readTextFileSync(path) === content) {
      return;
    }
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) {
      throw error;
    }
  }

  Deno.writeTextFileSync(path, content);
}

writeTextFileIfChanged(`${root}/progress-sidebar.js`, script);
writeTextFileIfChanged(`${root}/progress-sidebar.html`, html);
